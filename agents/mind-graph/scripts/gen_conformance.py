#!/usr/bin/env python3
"""Generate the cross-runtime conformance fixture.

    python3 scripts/gen_conformance.py

⭐ **This file is the mechanism that makes §4.4 safe.** The portable payload
splits ranking into a server half and a client half; this pins the client half
so the two runtimes cannot drift apart silently.

It writes a fixture containing a real portable payload and the ranking Python
produces from it. `Frontend_build` loads the same fixture, runs its own
`rankPortable`, and asserts identical output — same order, same scores to five
decimals.

⚠️ If you change `DISTANCE_PENALTY`, the weight vector, or the DOI components,
**regenerate this and run the frontend test.** A failure here is the system
telling you the Map is about to rank differently from the Bench.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from mindgraph.artifact import Session, measure, predict          # noqa: E402
from mindgraph.coldstart import seed_project                       # noqa: E402
from mindgraph.extract import FakeLLM, ingest_text                 # noqa: E402
from mindgraph.portable import rank_portable, to_portable          # noqa: E402
from mindgraph.proposals import ingest                             # noqa: E402

OUT = ROOT.parent / "Frontend_build" / "src" / "lib" / "__fixtures__" / "conformance.json"
Q = "Can skin impedance track hydration to within 10 percent?"


def build(tmp: Path):
    """A graph with enough shape to exercise every DOI component.

    ⚠️ A trivial graph would pass conformance while proving nothing — the
    components that differ (outcome, staleness, learnability) only become
    non-zero once there are measurements and a frontier.
    """
    s = Session.open("conf", tmp)
    seed_project(s, Q)
    ingest(s, ingest_text("lab_notes.md",
                          "skin impedance drops when hydrated\n"
                          "electrode drift dominates below 1 kHz\n"
                          "dry electrodes add contact impedance over gel\n",
                          FakeLLM()))
    for lo, hi, val, label in ((45, 50, 47.2, "Forearm sweep, dry electrodes"),
                               (30, 40, 33.0, "Gel-electrode control"),
                               (0, 5, 11.4, "Motion-artifact rejection")):
        aid = predict(s, label=label, quantity="impedance", low=lo, high=hi,
                      unit="kOhm")
        measure(s, aid, value=val)
    st = s.state()
    seeds = sorted(st.nodes)[:3]
    payload = to_portable(st, seeds=seeds)
    s.close()
    return payload


def main() -> int:
    import tempfile
    with tempfile.TemporaryDirectory() as tmp:
        payload = build(Path(tmp))
    ranking = rank_portable(payload)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps({
        "_note": "GENERATED by Backend_build/scripts/gen_conformance.py — do not "
                 "hand-edit. Pins the client's ranking to the server's.",
        "payload": payload,
        "expected": [{"id": i, "score": sc} for i, sc in ranking],
    }, indent=1, sort_keys=True))
    print(f"  wrote {OUT.relative_to(ROOT.parent)}")
    print(f"  {len(payload['nodes'])} nodes · {len(payload['edges'])} edges")
    print(f"  top: {ranking[0][0][:8]}… {ranking[0][1]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
